# Задача 22: Даны два неупорядоченных набора целых чисел (может быть, с повторениями).
# Выдать без повторений в порядке возрастания все те числа, которые встречаются в обоих наборах.
# Пользователь вводит 2 числа. n — кол-во элементов первого множества.
# m — кол-во элементов второго множества. Затем пользователь вводит сами элементы множеств.

# Считываем количество элементов для обоих наборов
n, m = map(int, input().split())

# Считываем элементы первого и второго набора, сразу преобразуя их во множества
set1 = set(map(int, input().split()))
set2 = set(map(int, input().split()))

# Находим пересечение множеств (элементы, которые есть в обоих наборах)
result = set1.intersection(set2)

# Сортируем по возрастанию и выводим через пробел
print(*sorted(result))